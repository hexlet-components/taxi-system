-- Логическая репликация вместо потокового копирования: подписка поднимается
-- чистым SQL, поэтому у реплики нет своего entrypoint и pg_basebackup.
-- Таблицы перечислены явно: FOR ALL TABLES затянул бы в публикацию таблицы,
-- которые решение создаёт миграциями, и подписка встала бы на первой строке
-- для таблицы, которой на реплике нет.
CREATE PUBLICATION taxi FOR TABLE passengers, drivers, trips, trip_events;
